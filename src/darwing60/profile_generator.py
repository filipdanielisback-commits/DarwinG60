"""Generate starter metadata for a new DarwinG60 device research profile.

This creates repository files only. It never communicates with a device or
changes firmware, partitions, boot settings, or hardware.
"""
from __future__ import annotations

import json
import re
from pathlib import Path

CODENAME_PATTERN = re.compile(r"^[a-z0-9][a-z0-9_-]{0,47}$")


def validate_identity(codename: str, manufacturer: str, marketing_name: str) -> None:
    if not CODENAME_PATTERN.fullmatch(codename):
        raise ValueError(
            "Codename must be 1-48 lowercase letters, numbers, hyphens, or underscores."
        )
    if not manufacturer.strip():
        raise ValueError("Manufacturer cannot be empty.")
    if not marketing_name.strip():
        raise ValueError("Marketing name cannot be empty.")


def build_templates(codename: str, manufacturer: str, marketing_name: str) -> dict[str, str]:
    """Return starter files with unknown hardware values left blank."""
    validate_identity(codename, manufacturer, marketing_name)
    device = {
        "schema_version": 1,
        "project": "DarwinG60",
        "device": {
            "manufacturer": manufacturer.strip(),
            "marketing_name": marketing_name.strip(),
            "codename": codename,
            "model_numbers": [],
        },
        "platform": {
            "soc_marketing_name": None,
            "architecture": "unknown",
            "soc_internal_id": None,
        },
        "memory_and_storage": {
            "ram_gb_options": [],
            "storage_gb_options": [],
        },
        "display": {
            "resolution_pixels": None,
            "panel": None,
            "refresh_rate_hz": None,
        },
        "battery": {"capacity_mah_typical": None},
        "research_status": {
            "hardware_probed_by_darwing60": False,
            "bootloader_implemented": False,
            "kernel_ported": False,
            "device_drivers_implemented": False,
            "bootable_image_available": False,
        },
        "notes": [
            "Starter template generated by DarwinG60 profile generator.",
            "Unknown values are intentionally null or empty; verify every specification using reliable sources.",
            "Metadata only. This profile does not indicate device support.",
        ],
    }
    compatibility = {
        "schema_version": 1,
        "device_codename": codename,
        "overall_status": "research_only",
        "components": [
            {
                "name": name,
                "status": "unknown",
                "evidence": "Research required.",
                "darwing60_implementation": "None",
            }
            for name in (
                "Boot architecture / firmware",
                "ARM64 CPU environment",
                "Memory and interrupt controller",
                "Display and touch",
                "Storage",
                "Wi-Fi and Bluetooth",
                "Battery and charging",
                "Audio",
                "Camera and sensors",
                "GPU",
                "Kernel boot",
            )
        ],
        "safety_boundary": (
            "Research and host-side metadata only. No device modification or "
            "firmware operations are performed by this profile."
        ),
    }
    return {
        "device.json": json.dumps(device, indent=2) + "\n",
        "compatibility.json": json.dumps(compatibility, indent=2) + "\n",
        "sources.md": (
            f"# Sources for {marketing_name} ({codename})\n\n"
            "Add links to reliable public documentation here. For each hardware "
            "claim, record the source, date checked, and any regional/model "
            "limitations. Do not treat community claims as verified specifications.\n"
        ),
        "README.md": (
            f"# {marketing_name} ({codename})\n\n"
            f"- Manufacturer: {manufacturer}\n"
            "- Research status: research only\n"
            "- DarwinG60 hardware support: not implemented or validated\n\n"
            "Complete the device metadata and compatibility matrix using "
            "reliable sources. Unknown values must remain unknown. See "
            "[porting documentation](../../docs/porting/README.md).\n"
        ),
    }


def generate_profile(
    device_root: Path, codename: str, manufacturer: str, marketing_name: str
) -> Path:
    """Create a new profile directory; refuse to overwrite existing files."""
    templates = build_templates(codename, manufacturer, marketing_name)
    target = device_root / codename
    if target.exists():
        raise FileExistsError(f"Device profile already exists: {codename}")
    target.mkdir(parents=True)
    try:
        for filename, content in templates.items():
            (target / filename).write_text(content, encoding="utf-8")
    except OSError:
        # Remove only files created by this invocation if writing fails.
        for filename in templates:
            candidate = target / filename
            if candidate.exists():
                candidate.unlink()
        target.rmdir()
        raise
    return target
